"""Create a separate Rozetka YML feed using the freshly generated EVA feed.

KeyCRM is queried only once by generate_feed.py. This adapter retains
stable offer/category IDs, inventory and photos; the EVA feed is unchanged.
"""
from copy import deepcopy
from pathlib import Path
import xml.etree.ElementTree as ET
from urllib.parse import urlsplit

SOURCE = Path("pricelists/eva.xml")
OUTPUT = Path("pricelists/rozetka.xml")
REQUIRED_FIELDS = ("price", "currencyId", "categoryId", "picture",
                   "vendor", "stock_quantity", "name", "description")


def convert(root):
    if root.tag != "yml_catalog":
        raise ValueError("Expected YML catalog generated by generate_feed.py")
    result = deepcopy(root)
    shop = result.find("shop")
    if shop is None or shop.find("categories") is None:
        raise ValueError("Missing shop/categories")
    categories = {node.get("id") for node in shop.findall("./categories/category")}
    offers = shop.find("offers")
    if offers is None or len(offers) == 0:
        raise ValueError("No offers in KeyCRM feed")
    seen_ids, seen_names = set(), set()
    for offer in offers.findall("offer"):
        offer_id = offer.get("id")
        if not offer_id or not offer_id.isascii() or not offer_id.isalnum() or offer_id in seen_ids:
            raise ValueError(f"Invalid/duplicate offer ID: {offer_id!r}")
        seen_ids.add(offer_id)
        if offer.findtext("categoryId") not in categories:
            raise ValueError(f"Unknown category for offer {offer_id}")
        name_ua = (offer.findtext("name_ua") or "").strip()
        description_ua = (offer.findtext("description_ua") or "").strip()
        if not name_ua or not description_ua:
            raise ValueError(f"Missing Ukrainian product copy for offer {offer_id}")
        if name_ua in seen_names:
            raise ValueError(f"Duplicate product name: {name_ua}")
        seen_names.add(name_ua)
        # Rozetka requires generic name/description even when _ua versions exist.
        # Ukrainian content is acceptable in both sets; don't invent Russian.
        ET.SubElement(offer, "name").text = name_ua
        ET.SubElement(offer, "description").text = description_ua
        for field in REQUIRED_FIELDS:
            if not (offer.findtext(field) or "").strip():
                raise ValueError(f"Missing {field} for offer {offer_id}")
        try:
            stock = int(offer.findtext("stock_quantity"))
            price = float(offer.findtext("price"))
        except (ValueError, TypeError) as error:
            raise ValueError(f"Invalid stock/price for offer {offer_id}") from error
        if stock < 0 or price <= 0:
            raise ValueError(f"Invalid stock/price for offer {offer_id}")
        if offer.get("available") != str(stock > 0).lower():
            raise ValueError(f"Availability mismatch for offer {offer_id}")
        # Only export characteristics actually present in KeyCRM.
        for image in offer.findall("picture"):
            address = (image.text or "").strip()
            parsed = urlsplit(address)
            if (parsed.scheme != "https" or not parsed.netloc
                    or " " in address or "+" in address or any(ord(ch) > 127 for ch in address)):
                raise ValueError(f"Invalid Rozetka picture URL for offer {offer_id}")
    if len(seen_ids) != 3:
        raise ValueError(f"Expected three Verba Cosmetics products, got {len(seen_ids)}")
    ET.indent(result, space="  ")
    return ET.ElementTree(result)


def main():
    tree = convert(ET.parse(SOURCE).getroot())
    tmp = OUTPUT.with_suffix(".xml.tmp")
    tree.write(tmp, encoding="utf-8", xml_declaration=True)
    tmp.replace(OUTPUT)
    print(f"Rozetka YML generated: {OUTPUT}; offers: {len(tree.findall('./shop/offers/offer'))}")


if __name__ == "__main__":
    main()
